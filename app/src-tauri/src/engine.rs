//! The capture → recognition → counting loop, on its own thread.
//!
//! Publishes to the event bus: a status snapshot at most 10 Hz (or right
//! away when something happens), and each finished play after writing it
//! to `data.db`. The latest snapshot is also kept in [`SharedStatus`].

use std::path::PathBuf;
use std::sync::mpsc::{Receiver, Sender, TryRecvError};
use std::time::{Duration, Instant};

use chrono::{DateTime, Local, NaiveDate, NaiveTime, Utc};
use iu_capture::spout::SpoutReceiver;
use iu_capture::{CaptureError, FrameSource, RgbImage};
use iu_core::config::CaptureConfig;
use iu_core::counter::{Counter, CounterEvent, Observation};
use iu_core::day::game_day;
use iu_core::event::{Bus, Event};
use iu_core::status::{Connection, LastPlay, SharedStatus};
use iu_core::{Judge, PlayLayout};
use iu_db::{DATABASE_FILE_NAME, DaySummary, PlayRecord, Store};
use iu_recog::PlayResources;

/// Play resources per resolution, generated by `tools/resgen`.
pub(crate) const PLAY_RESOURCES: &[&str] =
    &[include_str!("../../../resources/1920x1080/play.json")];
/// Result-screen resources per resolution (only the annotator uses them
/// until result recognition is wired into the engine).
pub(crate) const RESULT_RESOURCES: &[&str] =
    &[include_str!("../../../resources/1920x1080/result.json")];

const RETRY_INTERVAL: Duration = Duration::from_secs(2);
/// Rebuild the receiver when the picture has not changed for this long.
const STALE_AFTER: Duration = Duration::from_secs(5);
const STATUS_INTERVAL: Duration = Duration::from_millis(100);
const DEV_CAPTURE_PLAY_INTERVAL: Duration = Duration::from_secs(10);
const DEV_CAPTURE_FAILURE_INTERVAL: Duration = Duration::from_secs(3);
/// An unreadable frame is saved only if the play screen is still there this
/// much later: when a song ends the screen dims for a second or two (longer
/// after a failed DP play), the panel is still detected but its digits are
/// too dark, and those frames are noise.
const DEV_CAPTURE_UNREADABLE_CONFIRM: Duration = Duration::from_secs(3);

pub enum Command {
    SetConfig(CaptureConfig),
    /// Save the latest frame now; replies with the file path.
    CaptureFrame(Sender<Result<PathBuf, String>>),
}

/// `day_start_jst` is read once: it only changes by editing `config.json`.
pub fn spawn(
    bus: Bus,
    config: CaptureConfig,
    day_start_jst: NaiveTime,
    data_dir: PathBuf,
    status: SharedStatus,
) -> Sender<Command> {
    let (tx, rx) = std::sync::mpsc::channel();
    std::thread::Builder::new()
        .name("engine".into())
        .spawn(move || Engine::new(bus, config, day_start_jst, data_dir, status).run(rx))
        .expect("spawn engine thread");
    tx
}

struct Engine {
    bus: Bus,
    config: CaptureConfig,
    /// `None` if `data.db` could not be opened: counting still works, but
    /// nothing is kept across restarts.
    store: Option<Store>,
    day_start_jst: NaiveTime,
    /// Current game day.
    day: NaiveDate,
    /// When the play in progress started, and its game day.
    play_started: Option<(DateTime<Utc>, NaiveDate)>,
    status: SharedStatus,
    resources: Vec<PlayResources>,
    receiver: Option<SpoutReceiver>,
    retry_at: Instant,
    counter: Counter,
    last_frame: Option<RgbImage>,
    last_change: Instant,
    last_fingerprint: u64,
    /// The "picture is stale" message was logged since the last change.
    stale_reported: bool,
    last_emit: Instant,
    last_play_capture: Instant,
    last_failure_capture: Instant,
    /// Unreadable frame waiting for [`DEV_CAPTURE_UNREADABLE_CONFIRM`].
    pending_unreadable: Option<(Instant, RgbImage)>,
}

impl Engine {
    fn new(
        bus: Bus,
        config: CaptureConfig,
        day_start_jst: NaiveTime,
        data_dir: PathBuf,
        status: SharedStatus,
    ) -> Self {
        let resources = PLAY_RESOURCES
            .iter()
            .filter_map(|json| match PlayResources::from_json(json) {
                Ok(r) => Some(r),
                Err(e) => {
                    tracing::error!("bundled play resources are broken: {e}");
                    None
                }
            })
            .collect();
        let db_path = data_dir.join(DATABASE_FILE_NAME);
        let store = Store::open(&db_path)
            .inspect_err(|e| tracing::error!("cannot open {}: {e}", db_path.display()))
            .ok();
        let day = game_day(Utc::now(), day_start_jst);
        let mut counter = Counter::default();
        if let Some(summary) = summary_of(store.as_ref(), day) {
            counter.today = summary.judge;
            counter.plays_today = summary.plays;
        }
        let last_play = store
            .as_ref()
            .and_then(|s| s.plays_on(day).inspect_err(|e| tracing::error!("{e}")).ok())
            .and_then(|plays| plays.last().map(|p| LastPlay::new(p.layout, p.judge)));
        status.lock().expect("status lock").last_play = last_play;
        let now = Instant::now();
        Self {
            bus,
            config,
            store,
            day_start_jst,
            day,
            play_started: None,
            status,
            resources,
            receiver: None,
            retry_at: now,
            counter,
            last_frame: None,
            last_change: now,
            last_fingerprint: 0,
            stale_reported: false,
            last_emit: now - STATUS_INTERVAL,
            last_play_capture: now,
            last_failure_capture: now - DEV_CAPTURE_FAILURE_INTERVAL,
            pending_unreadable: None,
        }
    }

    fn run(mut self, commands: Receiver<Command>) {
        tracing::info!(sender = %self.config.spout_sender, fps = self.config.fps, "engine started");
        self.publish(true);
        loop {
            let tick = Instant::now();
            loop {
                match commands.try_recv() {
                    Ok(cmd) => self.handle(cmd),
                    Err(TryRecvError::Empty) => break,
                    Err(TryRecvError::Disconnected) => return,
                }
            }
            self.roll_day();
            self.step();
            let interval = Duration::from_secs(1) / self.config.fps.clamp(1, 120);
            if let Some(rest) = interval.checked_sub(tick.elapsed()) {
                std::thread::sleep(rest);
            }
        }
    }

    fn handle(&mut self, cmd: Command) {
        match cmd {
            Command::SetConfig(config) => {
                if config.spout_sender != self.config.spout_sender {
                    self.receiver = None;
                    self.retry_at = Instant::now();
                }
                self.config = config;
                self.publish(true);
            }
            Command::CaptureFrame(reply) => {
                let result = match &self.last_frame {
                    Some(frame) => save_dev_capture(frame, "manual").map_err(|e| e.to_string()),
                    None => Err("no frame received yet".to_owned()),
                };
                let _ = reply.send(result);
            }
        }
    }

    fn step(&mut self) {
        if Instant::now() < self.retry_at {
            return;
        }
        if self.receiver.is_none() {
            match SpoutReceiver::new(&self.config.spout_sender) {
                Ok(r) => self.receiver = Some(r),
                Err(e) => return self.fail(Connection::Error, Some(e.to_string())),
            }
        }
        let receiver = self.receiver.as_mut().expect("created above");
        match receiver.next_frame() {
            Ok(Some(frame)) => self.on_frame(frame),
            Ok(None) => {}
            Err(CaptureError::SenderNotFound(_)) => self.fail(Connection::Waiting, None),
            Err(e) => {
                receiver.reset();
                self.fail(Connection::Error, Some(e.to_string()));
            }
        }
    }

    /// Lost the picture: end the play in progress and retry later.
    fn fail(&mut self, connection: Connection, detail: Option<String>) {
        if let Some(d) = &detail {
            tracing::warn!("capture: {d}");
        }
        self.observe(Observation::NotPlay);
        self.retry_at = Instant::now() + RETRY_INTERVAL;
        {
            let mut s = self.status.lock().expect("status lock");
            s.connection = connection;
            s.detail = detail;
            s.resolution = None;
            s.layout = None;
        }
        self.publish(false);
    }

    fn on_frame(&mut self, frame: RgbImage) {
        let fingerprint = fingerprint(&frame);
        if fingerprint != self.last_fingerprint {
            self.last_fingerprint = fingerprint;
            self.last_change = Instant::now();
            self.stale_reported = false;
        } else if self.last_change.elapsed() > STALE_AFTER {
            // A frozen picture is normal while the game is closed (OBS keeps
            // sending the last frame), so say it once, not every 5 s.
            if self.stale_reported {
                tracing::debug!("picture still unchanged; reconnecting");
            } else {
                tracing::info!("no picture change for {STALE_AFTER:?}; reconnecting");
                self.stale_reported = true;
            }
            if let Some(r) = self.receiver.as_mut() {
                r.reset();
            }
            self.last_change = Instant::now();
        }

        let dims = frame.dimensions();
        let Some(res) = self.resources.iter().find(|r| (r.width, r.height) == dims) else {
            {
                let mut s = self.status.lock().expect("status lock");
                s.connection = Connection::UnsupportedResolution;
                s.resolution = Some([dims.0, dims.1]);
            }
            self.last_frame = Some(frame);
            self.publish(false);
            return;
        };

        let (obs, failure) = match res.detect(&frame) {
            None => (Observation::NotPlay, None),
            Some(anchor) => match res.read_judge(&frame, &anchor) {
                Ok(judge) => (
                    Observation::Play {
                        layout: anchor.layout,
                        judge,
                    },
                    None,
                ),
                Err(e) => (
                    Observation::PlayUnreadable {
                        layout: anchor.layout,
                    },
                    Some(e),
                ),
            },
        };
        if let Some(e) = &failure {
            tracing::debug!("judge unreadable: {e}");
        }
        let rejected = self.observe(obs);
        self.dev_capture(&frame, &obs, failure.is_some() || rejected);

        {
            let mut s = self.status.lock().expect("status lock");
            s.connection = Connection::Connected;
            s.detail = None;
            s.resolution = Some([dims.0, dims.1]);
        }
        self.last_frame = Some(frame);
        self.publish(false);
    }

    /// Feeds the counter; returns true if the reading was rejected.
    fn observe(&mut self, obs: Observation) -> bool {
        let events = self.counter.observe(obs);
        let mut rejected = false;
        let mut finished = None;
        for ev in &events {
            match ev {
                CounterEvent::PlayStarted { layout } => {
                    tracing::info!(%layout, "play started");
                    self.play_started = Some((Utc::now(), self.day));
                }
                CounterEvent::PlayFinished { layout, judge } => {
                    tracing::info!(%layout, ?judge, notes = judge.notes_hit(), "play finished");
                    self.record_play(*layout, *judge);
                    // Entering and leaving without a single judgement keeps
                    // the previous song on screen.
                    if *judge != Judge::default() {
                        finished = Some(LastPlay::new(*layout, *judge));
                    }
                }
                CounterEvent::Rejected { reading, previous } => {
                    tracing::debug!(?reading, ?previous, "judge reading rejected");
                    rejected = true;
                }
                CounterEvent::JudgeUpdated { .. } => {}
            }
        }
        {
            let mut s = self.status.lock().expect("status lock");
            s.layout = self.counter.current.map(|c| c.layout.name().to_owned());
            s.current = self.counter.current.map(|c| c.judge);
            if finished.is_some() {
                s.last_play = finished;
            }
            s.today = self.counter.today_with_current();
            s.today_notes = s.today.notes_hit();
            s.plays_today = self.counter.plays_today;
        }
        let important = events
            .iter()
            .any(|e| !matches!(e, CounterEvent::JudgeUpdated { .. }));
        if important {
            self.publish(true);
        }
        rejected
    }

    fn dev_capture(&mut self, frame: &RgbImage, obs: &Observation, failed: bool) {
        if !self.config.dev_capture {
            self.pending_unreadable = None;
            return;
        }
        let in_play = !matches!(obs, Observation::NotPlay);
        if !in_play {
            self.pending_unreadable = None;
        } else if self
            .pending_unreadable
            .as_ref()
            .is_some_and(|(at, _)| at.elapsed() >= DEV_CAPTURE_UNREADABLE_CONFIRM)
        {
            let (_, pending) = self.pending_unreadable.take().expect("checked above");
            spawn_save(pending, "unreadable");
        }

        if failed
            && self.pending_unreadable.is_none()
            && self.last_failure_capture.elapsed() >= DEV_CAPTURE_FAILURE_INTERVAL
        {
            self.last_failure_capture = Instant::now();
            self.pending_unreadable = Some((Instant::now(), frame.clone()));
        } else if in_play && self.last_play_capture.elapsed() >= DEV_CAPTURE_PLAY_INTERVAL {
            self.last_play_capture = Instant::now();
            spawn_save(frame.clone(), "play");
        }
    }

    fn roll_day(&mut self) {
        let today = game_day(Utc::now(), self.day_start_jst);
        if today != self.day {
            tracing::info!(%today, "new game day: resetting today's totals");
            self.day = today;
            self.counter.reset_day();
            {
                let mut s = self.status.lock().expect("status lock");
                s.last_play = None;
                s.today = self.counter.today_with_current();
                s.today_notes = s.today.notes_hit();
                s.plays_today = self.counter.plays_today;
            }
            self.publish(true);
        }
    }

    /// Writes a finished play to `data.db`, then announces it. Writing here
    /// rather than in a bus listener guarantees the row exists by the time
    /// listeners (e.g. the phone page reloading its list) see the event.
    /// Plays with no judgements at all (entered and left right away) are not
    /// worth a row.
    fn record_play(&mut self, layout: PlayLayout, judge: Judge) {
        let finished_at = Utc::now();
        let (started_at, game_day) = self.play_started.take().unwrap_or((finished_at, self.day));
        if judge == Judge::default() {
            return;
        }
        let record = PlayRecord {
            game_day,
            started_at,
            finished_at,
            layout,
            judge,
        };
        if let Some(store) = &self.store
            && let Err(e) = store.insert_play(&record)
        {
            tracing::error!("cannot save the play to data.db: {e}");
        }
        // No receivers is fine (nothing listening yet).
        let _ = self.bus.send(Event::PlayFinished(record));
    }

    fn publish(&mut self, force: bool) {
        if !force && self.last_emit.elapsed() < STATUS_INTERVAL {
            return;
        }
        self.last_emit = Instant::now();
        let snapshot = {
            let mut s = self.status.lock().expect("status lock");
            s.sender = self.config.spout_sender.clone();
            s.dev_capture = self.config.dev_capture;
            s.clone()
        };
        let _ = self.bus.send(Event::Status(snapshot));
    }
}

/// Saves a dev capture on a worker thread: PNG encoding takes tens of ms
/// and must not stall the capture loop.
fn spawn_save(frame: RgbImage, reason: &'static str) {
    std::thread::spawn(move || {
        if let Err(e) = save_dev_capture(&frame, reason) {
            tracing::warn!("dev capture failed: {e}");
        }
    });
}

/// Cheap fingerprint of a frame: a sparse sample of pixels.
fn fingerprint(frame: &RgbImage) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    frame
        .as_raw()
        .iter()
        .step_by(997)
        .for_each(|b| b.hash(&mut h));
    h.finish()
}

fn summary_of(store: Option<&Store>, day: NaiveDate) -> Option<DaySummary> {
    store?
        .day_summary(day)
        .inspect_err(|e| tracing::error!("cannot read today's plays from data.db: {e}"))
        .ok()
}

/// `<Pictures>\INFINITAS Screenshots\dev-capture\<w>x<h>\unsorted\`.
pub fn dev_capture_dir(width: u32, height: u32) -> Option<PathBuf> {
    dirs::picture_dir().map(|p| {
        p.join("INFINITAS Screenshots")
            .join("dev-capture")
            .join(format!("{width}x{height}"))
            .join("unsorted")
    })
}

fn save_dev_capture(frame: &RgbImage, reason: &str) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let dir = dev_capture_dir(frame.width(), frame.height()).ok_or("no Pictures folder")?;
    std::fs::create_dir_all(&dir)?;
    let name = format!("{}_{reason}.png", Local::now().format("%Y%m%d_%H%M%S_%3f"));
    let path = dir.join(name);
    frame.save(&path)?;
    tracing::info!(path = %path.display(), "dev capture saved");
    Ok(path)
}
