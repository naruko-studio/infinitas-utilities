/// Play resources per resolution, generated by `tools/resgen`.
pub(crate) const PLAY_RESOURCES: &[&str] =
    &[include_str!("../../../resources/1920x1080/play.json")];
/// Result-screen resources per resolution.
pub(crate) const RESULT_RESOURCES: &[&str] =
    &[include_str!("../../../resources/1920x1080/result.json")];
/// Known title masks per resolution (from our labelled screenshots; the
/// app adds what it learns to `data.db`).
pub(crate) const TITLE_RESOURCES: &[&str] =
    &[include_str!("../../../resources/1920x1080/titles.json")];

const RETRY_INTERVAL: Duration = Duration::from_secs(2);
/// Rebuild the receiver when the picture has not changed for this long.
const STALE_AFTER: Duration = Duration::from_secs(5);
const STATUS_INTERVAL: Duration = Duration::from_millis(100);
const DEV_CAPTURE_PLAY_INTERVAL: Duration = Duration::from_secs(10);
const DEV_CAPTURE_FAILURE_INTERVAL: Duration = Duration::from_secs(3);
/// An unreadable frame is saved only if the play screen is still there this
/// much later: when a song ends the screen dims for a second or two (longer
/// after a failed DP play), the panel is still detected but its digits are
/// too dark, and those frames are noise.
const DEV_CAPTURE_UNREADABLE_CONFIRM: Duration = Duration::from_secs(3);
/// Frames kept from before play (one a second), for Intro screen samples.
const DEV_CAPTURE_INTRO_FRAMES: usize = 4;
/// Younger frames are the play screen fading in, not the Intro.
const DEV_CAPTURE_INTRO_MIN_AGE: Duration = Duration::from_millis(1500);

pub enum Command {
    SetConfig(CaptureConfig),
    /// Save the latest frame now; replies with the file path.
    CaptureFrame(Sender<Result<PathBuf, String>>),
    /// The user named the song of a stored result: record it, learn its
    /// title, and re-check the other unnamed results.
    NameResult {
        id: i64,
        song_id: String,
        reply: Sender<Result<(), String>>,
    },
}

/// How long a caller waits for the engine to answer a command.
pub const COMMAND_TIMEOUT: Duration = Duration::from_secs(5);

/// Asks the engine to name a stored result's song and waits for the answer.
pub fn name_result(engine: &Sender<Command>, id: i64, song_id: String) -> Result<(), String> {
    let (reply, rx) = std::sync::mpsc::channel();
    engine
        .send(Command::NameResult { id, song_id, reply })
        .map_err(|_| "the capture engine has stopped".to_owned())?;
    rx.recv_timeout(COMMAND_TIMEOUT)
        .map_err(|_| "the capture engine did not answer".to_owned())?
}

/// [`name_result`] for the web server.
pub fn name_result_fn(engine: Sender<Command>) -> iu_server::NameResult {
    std::sync::Arc::new(move |id, song_id| name_result(&engine, id, song_id))
}

/// `day_start_jst` is read once: it only changes by editing `config.json`.
pub fn spawn(
    bus: Bus,
    config: CaptureConfig,
    day_start_jst: NaiveTime,
    data_dir: PathBuf,
    status: SharedStatus,
) -> Sender<Command> {
    let (tx, rx) = std::sync::mpsc::channel();
    std::thread::Builder::new()
        .name("engine".into())
        .spawn(move || Engine::new(bus, config, day_start_jst, data_dir, status).run(rx))
        .expect("spawn engine thread");
    tx
}

struct Engine {
    bus: Bus,
    config: CaptureConfig,
    /// `None` if `data.db` could not be opened: counting still works, but
    /// nothing is kept across restarts.
    store: Option<Store>,
    day_start_jst: NaiveTime,
    /// Current game day.
    day: NaiveDate,
    /// When the play in progress started, and its game day.
    play_started: Option<(DateTime<Utc>, NaiveDate)>,
    status: SharedStatus,
    resources: Vec<PlayResources>,
    receiver: Option<SpoutReceiver>,
    retry_at: Instant,
    counter: Counter,
    last_frame: Option<RgbImage>,
    last_change: Instant,
    last_fingerprint: u64,
    /// The "picture is stale" message was logged since the last change.
    stale_reported: bool,
    last_emit: Instant,
    last_play_capture: Instant,
    last_failure_capture: Instant,
    /// Unreadable frame waiting for [`DEV_CAPTURE_UNREADABLE_CONFIRM`].
    pending_unreadable: Option<(Instant, RgbImage)>,
    /// Recent frames off the play screen (developer mode only).
    before_play: VecDeque<(Instant, RgbImage)>,
    result_resources: Vec<ResultResources>,
    /// Decides when the result screen's reading is final.
    results: ResultTracker<(ResultReading, ResultSymbols)>,
    /// The current visit to the result screen, for reporting one that is
    /// never recorded.
    result_visit: Option<ResultVisit>,
    title_resources: Vec<TitleResources>,
    /// Title masks learned on this machine (from `data.db`).
    learned_titles: Vec<KnownTitle>,
    ocr: OcrWorker,
    /// Looking for the song on the play screen: (style of the layout,
    /// last try, tries so far). `None` once found or given up.
    song_search: Option<SongSearch>,
    /// Play-screen title masks learned on this machine, per layout.
    learned_play_titles: Vec<(PlayLayout, KnownTitle)>,
    /// The current (or last) play's info-box title mask, learned once the
    /// play's song is known.
    play_title: Option<PlayTitle>,
}

/// The title line of a play's info box.
struct PlayTitle {
    layout: PlayLayout,
    mask: TitleMask,
    taken: Instant,
    takes: u32,
    /// The result recorded for this play while its song was unknown (the
    /// user may name it later).
    unnamed_result: Option<i64>,
}

/// A visit to the result screen that has not been recorded yet.
struct ResultVisit {
    since: Instant,
    /// Why the last frame was not accepted.
    problem: String,
    reported: bool,
}

/// A result screen still not recorded after this long is reported (and
/// captured in developer mode): its reading fails or never settles.
const RESULT_REPORT_AFTER: Duration = Duration::from_secs(2);
/// Longest wait for OCR of a result title (the engine waits for it once
/// per result, off the play screen).
const OCR_RESULT_WAIT: Duration = Duration::from_secs(3);
/// The play screen's info box is read this often until the song is found…
const SONG_SEARCH_EVERY: Duration = Duration::from_secs(1);
/// …at most this many times per play.
const SONG_SEARCH_TRIES: u32 = 8;
/// The play screen's title line is taken this often…
const PLAY_TITLE_EVERY: Duration = Duration::from_secs(1);
/// …this many times per play (the last is kept: by then the box has
/// finished fading in).
const PLAY_TITLE_TAKES: u32 = 5;
/// A play-screen title mask this close to a learned one is that song. The
/// text is static: the same song measured ≤ 52 apart (while EXTRA STAGE
/// above it was fading), different songs ≥ 629.
const PLAY_TITLE_MAX_DISTANCE: u32 = 150;
/// Fewer ink pixels than this is no title (the box is not drawn yet).
const PLAY_TITLE_MIN_INK: u32 = 40;

impl Engine {
    fn new(
        bus: Bus,
        config: CaptureConfig,
        day_start_jst: NaiveTime,
        data_dir: PathBuf,
        status: SharedStatus,
    ) -> Self {
        let resources = PLAY_RESOURCES
            .iter()
            .filter_map(|json| match PlayResources::from_json(json) {
                Ok(r) => Some(r),
                Err(e) => {
                    tracing::error!("bundled play resources are broken: {e}");
                    None
                }
            })
            .collect();
        let db_path = data_dir.join(DATABASE_FILE_NAME);
        let store = Store::open(&db_path)
            .inspect_err(|e| tracing::error!("cannot open {}: {e}", db_path.display()))
            .ok();
        let day = game_day(Utc::now(), day_start_jst);
        let mut counter = Counter::default();
        if let Some(summary) = summary_of(store.as_ref(), day) {
            counter.today = summary.judge;
            counter.plays_today = summary.plays;
        }
        let last_play = store
            .as_ref()
            .and_then(|s| s.plays_on(day).inspect_err(|e| tracing::error!("{e}")).ok())
            .and_then(|plays| plays.last().map(|p| LastPlay::new(p.layout, p.judge)));
        let last_result = store
            .as_ref()
            .and_then(|s| {
                s.results_on(day)
                    .inspect_err(|e| tracing::error!("{e}"))
                    .ok()
            })
            .and_then(|r| r.last().cloned());
        {
            let mut s = status.lock().expect("status lock");
            s.last_play = last_play;
            s.last_result = last_result;
        }
        let learned_titles = store
            .as_ref()
            .and_then(|s| {
                s.learned_titles()
                    .inspect_err(|e| tracing::error!("{e}"))
                    .ok()
            })
            .unwrap_or_default()
            .into_iter()
            .filter_map(|(song_id, m)| {
                Some(KnownTitle {
                    song_id,
                    mask: TitleMask::from_bytes(m.width, m.height, &m.bytes)?,
                })
            })
            .collect();
        let learned_play_titles = store
            .as_ref()
            .and_then(|s| {
                s.learned_play_titles()
                    .inspect_err(|e| tracing::error!("{e}"))
                    .ok()
            })
            .unwrap_or_default()
            .into_iter()
            .filter_map(|(song_id, layout, m)| {
                Some((
                    layout.parse().ok()?,
                    KnownTitle {
                        song_id,
                        mask: TitleMask::from_bytes(m.width, m.height, &m.bytes)?,
                    },
                ))
            })
            .collect();
        let now = Instant::now();
        Self {
            bus,
            config,
            store,
            day_start_jst,
            day,
            play_started: None,
            status,
            resources,
            receiver: None,
            retry_at: now,
            counter,
            last_frame: None,
            last_change: now,
            last_fingerprint: 0,
            stale_reported: false,
            last_emit: now - STATUS_INTERVAL,
            last_play_capture: now,
            last_failure_capture: now - DEV_CAPTURE_FAILURE_INTERVAL,
            pending_unreadable: None,
            before_play: VecDeque::new(),
            result_resources: RESULT_RESOURCES
                .iter()
                .filter_map(|json| {
                    ResultResources::from_json(json)
                        .inspect_err(|e| {
                            tracing::error!("bundled result resources are broken: {e}")
                        })
                        .ok()
                })
                .collect(),
            results: ResultTracker::default(),
            result_visit: None,
            title_resources: TITLE_RESOURCES
                .iter()
                .filter_map(|json| {
                    TitleResources::from_json(json)
                        .inspect_err(|e| tracing::error!("bundled title resources are broken: {e}"))
                        .ok()
                })
                .collect(),
            learned_titles,
            ocr: OcrWorker::spawn(),
            song_search: None,
            learned_play_titles,
            play_title: None,
        }
    }

    fn run(mut self, commands: Receiver<Command>) {
        tracing::info!(sender = %self.config.spout_sender, fps = self.config.fps, "engine started");
        self.publish(true);
        loop {
            let tick = Instant::now();
            loop {
                match commands.try_recv() {
                    Ok(cmd) => self.handle(cmd),
                    Err(TryRecvError::Empty) => break,
                    Err(TryRecvError::Disconnected) => return,
                }
            }
            self.roll_day();
            self.step();
            let interval = Duration::from_secs(1) / self.config.fps.clamp(1, 120);
            if let Some(rest) = interval.checked_sub(tick.elapsed()) {
                std::thread::sleep(rest);
            }
        }
    }

    fn handle(&mut self, cmd: Command) {
        match cmd {
            Command::SetConfig(config) => {
                if config.spout_sender != self.config.spout_sender {
                    self.receiver = None;
                    self.retry_at = Instant::now();
                }
                self.config = config;
                self.publish(true);
            }
            Command::CaptureFrame(reply) => {
                let result = match &self.last_frame {
                    Some(frame) => save_dev_capture(frame, "manual").map_err(|e| e.to_string()),
                    None => Err("no frame received yet".to_owned()),
                };
                let _ = reply.send(result);
            }
            Command::NameResult { id, song_id, reply } => {
                let _ = reply.send(self.name_result(id, &song_id));
            }
        }
    }

    fn step(&mut self) {
        if Instant::now() < self.retry_at {
            return;
        }
        if self.receiver.is_none() {
            match SpoutReceiver::new(&self.config.spout_sender) {
                Ok(r) => self.receiver = Some(r),
                Err(e) => return self.fail(Connection::Error, Some(e.to_string())),
            }
        }
        let receiver = self.receiver.as_mut().expect("created above");
        match receiver.next_frame() {
            Ok(Some(frame)) => self.on_frame(frame),
            Ok(None) => {}
            Err(CaptureError::SenderNotFound(_)) => self.fail(Connection::Waiting, None),
            Err(e) => {
                receiver.reset();
                self.fail(Connection::Error, Some(e.to_string()));
            }
        }
    }

    /// Lost the picture: end the play in progress and retry later.
    fn fail(&mut self, connection: Connection, detail: Option<String>) {
        if let Some(d) = &detail {
            tracing::warn!("capture: {d}");
        }
        self.observe(Observation::NotPlay);
        self.retry_at = Instant::now() + RETRY_INTERVAL;
        {
            let mut s = self.status.lock().expect("status lock");
            s.connection = connection;
            s.detail = detail;
            s.resolution = None;
            s.layout = None;
        }
        self.publish(false);
    }

    fn on_frame(&mut self, frame: RgbImage) {
        let fingerprint = fingerprint(&frame);
        if fingerprint != self.last_fingerprint {
            self.last_fingerprint = fingerprint;
            self.last_change = Instant::now();
            self.stale_reported = false;
        } else if self.last_change.elapsed() > STALE_AFTER {
            // A frozen picture is normal while the game is closed (OBS keeps
            // sending the last frame), so say it once, not every 5 s.
            if self.stale_reported {
                tracing::debug!("picture still unchanged; reconnecting");
            } else {
                tracing::info!("no picture change for {STALE_AFTER:?}; reconnecting");
                self.stale_reported = true;
            }
            if let Some(r) = self.receiver.as_mut() {
                r.reset();
            }
            self.last_change = Instant::now();
        }

        let dims = frame.dimensions();
        let Some(res) = self.resources.iter().find(|r| (r.width, r.height) == dims) else {
            {
                let mut s = self.status.lock().expect("status lock");
                s.connection = Connection::UnsupportedResolution;
                s.resolution = Some([dims.0, dims.1]);
            }
            self.last_frame = Some(frame);
            self.publish(false);
            return;
        };

        let (obs, failure) = match res.detect(&frame) {
            None => (Observation::NotPlay, None),
            Some(anchor) => match res.read_judge(&frame, &anchor) {
                Ok(judge) => (
                    Observation::Play {
                        layout: anchor.layout,
                        judge,
                    },
                    None,
                ),
                Err(e) => (
                    Observation::PlayUnreadable {
                        layout: anchor.layout,
                    },
                    Some(e),
                ),
            },
        };
        if let Some(e) = &failure {
            tracing::debug!("judge unreadable: {e}");
        }
        let rejected = self.observe(obs);
        if matches!(obs, Observation::NotPlay) {
            self.check_result(&frame);
        } else {
            self.results.observe(None);
            self.result_visit = None;
        }
        self.dev_capture(&frame, &obs, failure.is_some() || rejected);
        self.search_song(&frame, !matches!(obs, Observation::NotPlay));

        {
            let mut s = self.status.lock().expect("status lock");
            s.connection = Connection::Connected;
            s.detail = None;
            s.resolution = Some([dims.0, dims.1]);
        }
        self.last_frame = Some(frame);
        self.publish(false);
    }

    /// While a play has no song yet, reads the play screen's info box now
    /// and then (on the OCR thread), and takes in finished reads.
    fn search_song(&mut self, frame: &RgbImage, in_play: bool) {
        self.take_ocr_results();
        if in_play {
            self.watch_play_title(frame);
        }
        let Some(search) = self.song_search.as_mut() else {
            return;
        };
        if !in_play || search.tries >= SONG_SEARCH_TRIES {
            if search.tries >= SONG_SEARCH_TRIES {
                tracing::info!("song not found on the play screen");
            }
            self.song_search = None;
            return;
        }
        if search
            .last_try
            .is_some_and(|t| t.elapsed() < SONG_SEARCH_EVERY)
        {
            return;
        }
        let (w, h) = frame.dimensions();
        let (Some(band), Some(info)) = (
            iu_ocr::areas::play_band(w, h),
            iu_ocr::areas::play_info(w, h, search.layout),
        ) else {
            self.song_search = None;
            return;
        };
        let areas = vec![(band, 1), (info, iu_ocr::areas::PLAY_INFO_SCALE)];
        if self.ocr.request(Purpose::PlayInfo, frame, areas) {
            search.last_try = Some(Instant::now());
            search.tries += 1;
        }
    }

    /// Takes the play's info-box title line now and then; while the song is
    /// not known, a learned mask may name it (OCR misses one-letter titles).
    fn watch_play_title(&mut self, frame: &RgbImage) {
        let Some(layout) = self.counter.current.map(|c| c.layout) else {
            return;
        };
        let takes = match &self.play_title {
            Some(p) if p.layout == layout => {
                if p.takes >= PLAY_TITLE_TAKES || p.taken.elapsed() < PLAY_TITLE_EVERY {
                    return;
                }
                p.takes
            }
            _ => 0,
        };
        let (w, h) = frame.dimensions();
        let Some(area) = play_title_area(w, h, layout) else {
            return;
        };
        let mask = TitleMask::from_image(frame, area);
        let inked = mask.count_ones() >= PLAY_TITLE_MIN_INK;
        let found = self
            .song_search
            .as_ref()
            .filter(|_| inked)
            .and_then(|_| {
                let known = self
                    .learned_play_titles
                    .iter()
                    .filter(|(l, _)| *l == layout)
                    .map(|(_, k)| k);
                best_match(&mask, known, None, PLAY_TITLE_MAX_DISTANCE)
            })
            .map(|(id, distance)| (id.to_owned(), distance));
        self.play_title = Some(PlayTitle {
            layout,
            mask,
            taken: Instant::now(),
            takes: takes + 1,
            unnamed_result: None,
        });
        if let Some((id, distance)) = found
            && let Some(song) = song_list().get(&id)
        {
            tracing::info!(title = %song.title, distance, "song found by its learned play-screen title");
            self.song_search = None;
            self.status.lock().expect("status lock").current_song = Some(SongRef::from(song));
            self.publish(true);
        }
    }

    /// Keeps the last play's title mask for this song, unless one close
    /// enough is known for its layout.
    fn learn_play_title(&mut self, song_id: &str) {
        let Some(p) = &self.play_title else {
            return;
        };
        if p.mask.count_ones() < PLAY_TITLE_MIN_INK {
            return;
        }
        let known = self.learned_play_titles.iter().any(|(l, k)| {
            *l == p.layout
                && k.song_id == song_id
                && k.mask.distance(&p.mask) <= PLAY_TITLE_MAX_DISTANCE / 2
        });
        if known {
            return;
        }
        if let Some(store) = &self.store
            && let Err(e) =
                store.learn_play_title(song_id, p.layout.name(), &mask_data(&p.mask), Utc::now())
        {
            tracing::error!("cannot save a learned play-screen title: {e}");
            return;
        }
        tracing::info!(song_id, layout = %p.layout, "play-screen title learned");
        self.learned_play_titles.push((
            p.layout,
            KnownTitle {
                song_id: song_id.to_owned(),
                mask: p.mask.clone(),
            },
        ));
    }

    fn take_ocr_results(&mut self) {
        while let Some((purpose, lines)) = self.ocr.poll() {
            if purpose == Purpose::PlayInfo {
                self.on_play_info(&lines);
            }
        }
        let available = self.ocr.available();
        let mut s = self.status.lock().expect("status lock");
        if s.ocr_available != available {
            s.ocr_available = available;
            drop(s);
            self.publish(true);
        }
    }

    /// Lines read from the play screen's top band: the song, if they name
    /// one of this play style.
    fn on_play_info(&mut self, lines: &[String]) {
        let Some(search) = &self.song_search else {
            return;
        };
        let dp = matches!(search.layout, PlayLayout::Dp { .. });
        let songs = song_list()
            .songs
            .iter()
            .filter(|s| s.charts.keys().any(|c| c.key().starts_with("DP") == dp));
        let Some(m) = match_text(lines, songs) else {
            tracing::debug!(?lines, "play screen read, no song yet");
            return;
        };
        tracing::info!(title = %m.song.title, score = m.score, "song found on the play screen");
        self.song_search = None;
        self.status.lock().expect("status lock").current_song = Some(SongRef::from(m.song));
        self.publish(true);
    }

    /// Off the play screen: if this is a result screen, read it, and once
    /// the reading is stable record it (once per visit).
    fn check_result(&mut self, frame: &RgbImage) {
        let Some(res) = self
            .result_resources
            .iter()
            .find(|r| (r.width, r.height) == frame.dimensions())
        else {
            return;
        };
        let Some(side) = res.detect(frame) else {
            self.results.observe(None);
            self.result_visit = None;
            return;
        };
        let reading = match res.read(frame, side) {
            Ok(r) => r,
            Err(e) => {
                tracing::debug!("result unreadable: {e}");
                self.results.unreadable();
                self.note_unrecorded_result(frame, format!("unreadable: {e}"));
                return;
            }
        };
        let symbols = res.read_symbols(frame, side);
        let recorded = self.results.observe(Some((reading, symbols.clone())));
        if recorded.is_none() {
            if !self.results.recorded() {
                self.note_unrecorded_result(
                    frame,
                    format!("not settled yet: {reading:?} {symbols:?}"),
                );
            }
        } else {
            self.result_visit = None;
        }
        if let Some((r, s)) = recorded {
            if self.config.dev_capture {
                // Every recorded result is a labelling sample; unknown words
                // (a class not learned yet) are marked in the name.
                let known = s.lamp.is_some()
                    && s.dj_level.is_some()
                    && s.chart.is_some()
                    && s.best_lamp.is_some()
                    && s.best_dj_level.is_some();
                spawn_save(
                    frame.clone(),
                    if known { "result" } else { "result-unknown" },
                );
            }
            let title = self
                .title_resources
                .iter()
                .find_map(|t| t.mask(frame).map(|m| (t, m)));
            let title = title.map(|(res, mask)| (mask, res.max_distance));
            self.record_result(frame, r, s, title);
        }
    }

    /// Every known title mask: bundled for this mask's size, then learned.
    fn known_titles(&self) -> impl Iterator<Item = &KnownTitle> {
        self.title_resources
            .iter()
            .flat_map(|t| &t.titles)
            .chain(&self.learned_titles)
    }

    /// The song of a result screen from its chart, level, NOTES count and
    /// title line (see [`identify`]).
    fn identify_song(
        &self,
        chart: Option<Chart>,
        level: Option<u8>,
        notes: u32,
        mask: &TitleMask,
        max_distance: u32,
    ) -> TitleMatch {
        let candidates: Vec<&str> = song_list()
            .candidates(chart, level, notes)
            .into_iter()
            .map(|s| s.id.as_str())
            .collect();
        identify(mask, self.known_titles(), &candidates, max_distance)
    }

    /// Keeps a title mask for this song, unless one close enough is known.
    fn learn_title(&mut self, song_id: &str, mask: &TitleMask, max_distance: u32) {
        let known = self
            .known_titles()
            .any(|k| k.song_id == song_id && k.mask.distance(mask) <= max_distance / 2);
        if known {
            return;
        }
        if let Some(store) = &self.store
            && let Err(e) = store.learn_title(song_id, &mask_data(mask), Utc::now())
        {
            tracing::error!("cannot save a learned title: {e}");
            return;
        }
        tracing::info!(song_id, "title learned");
        self.learned_titles.push(KnownTitle {
            song_id: song_id.to_owned(),
            mask: mask.clone(),
        });
    }

    /// The user named a stored result's song: store it, learn the title
    /// mask, then try the other unnamed results again with what was learned.
    fn name_result(&mut self, id: i64, song_id: &str) -> Result<(), String> {
        let song = song_list()
            .get(song_id)
            .ok_or_else(|| format!("unknown song {song_id}"))?;
        let store = self.store.as_ref().ok_or("data.db is not open")?;
        let unnamed = store.unnamed_results().map_err(|e| e.to_string())?;
        let target = unnamed
            .iter()
            .find(|u| u.record.id == Some(id))
            .ok_or_else(|| format!("result {id} has no title mask or is named already"))?;
        let max_distance = self.title_resources.first().map_or(0, |t| t.max_distance);
        let mask = TitleMask::from_bytes(target.mask.width, target.mask.height, &target.mask.bytes)
            .ok_or("stored title mask is broken")?;
        self.set_song(id, song_id, &song.title)?;
        self.learn_title(song_id, &mask, max_distance);
        if self
            .play_title
            .as_ref()
            .is_some_and(|p| p.unnamed_result == Some(id))
        {
            self.learn_play_title(song_id);
        }
        for other in unnamed.iter().filter(|u| u.record.id != Some(id)) {
            let (Some(other_id), Some(m)) = (
                other.record.id,
                TitleMask::from_bytes(other.mask.width, other.mask.height, &other.mask.bytes),
            ) else {
                continue;
            };
            let r = &other.record;
            if let TitleMatch::Recognized { song_id, .. } | TitleMatch::OnlyCandidate(song_id) =
                self.identify_song(r.chart, r.level, r.notes, &m, max_distance)
                && let Some(song) = song_list().get(&song_id)
            {
                self.set_song(other_id, &song_id, &song.title)?;
            }
        }
        Ok(())
    }

    /// Stores a result's song and tells everyone.
    fn set_song(&mut self, id: i64, song_id: &str, title: &str) -> Result<(), String> {
        let store = self.store.as_ref().ok_or("data.db is not open")?;
        store
            .set_result_song(id, song_id, title)
            .map_err(|e| e.to_string())?;
        let Some(record) = store.result(id).map_err(|e| e.to_string())? else {
            return Ok(());
        };
        tracing::info!(id, song_id, title, "result named");
        {
            let mut s = self.status.lock().expect("status lock");
            if s.last_result.as_ref().and_then(|r| r.id) == Some(id) {
                s.last_result = Some(record.clone());
            }
        }
        let _ = self.bus.send(Event::ResultUpdated(record));
        self.publish(true);
        Ok(())
    }

    /// A result screen frame that was not recorded. Once the visit has gone
    /// on for [`RESULT_REPORT_AFTER`] without a record, say why (once), and
    /// in developer mode keep the frame for diagnosis.
    fn note_unrecorded_result(&mut self, frame: &RgbImage, problem: String) {
        let visit = self.result_visit.get_or_insert_with(|| ResultVisit {
            since: Instant::now(),
            problem: String::new(),
            reported: false,
        });
        visit.problem = problem;
        if visit.reported || visit.since.elapsed() < RESULT_REPORT_AFTER {
            return;
        }
        visit.reported = true;
        tracing::warn!(
            "result screen not recorded after {RESULT_REPORT_AFTER:?}: {}",
            visit.problem
        );
        if self.config.dev_capture {
            spawn_save(frame.clone(), "result-unreadable");
        }
    }

    /// The song of a result screen, in order: the only song with this
    /// chart, level and NOTES count; a learned title mask; the song read
    /// from the play screen's info box; OCR of the result's title line.
    fn find_result_song(
        &mut self,
        frame: &RgbImage,
        r: &ResultReading,
        s: &ResultSymbols,
        title: Option<&(TitleMask, u32)>,
    ) -> (Option<String>, SongSource) {
        let songs = song_list();
        let candidates = songs.candidates(s.chart, s.level, r.notes);
        let allowed = |id: &str| candidates.is_empty() || candidates.iter().any(|c| c.id == id);
        if let Some((mask, max_distance)) = title {
            match self.identify_song(s.chart, s.level, r.notes, mask, *max_distance) {
                TitleMatch::OnlyCandidate(id) => return (Some(id), SongSource::OnlyCandidate),
                TitleMatch::Recognized { song_id, distance } => {
                    return (Some(song_id), SongSource::LearnedTitle { distance });
                }
                TitleMatch::Unknown => {}
            }
        }
        let playing = self
            .status
            .lock()
            .expect("status lock")
            .current_song
            .clone();
        if let Some(song) = playing.filter(|p| allowed(&p.id)) {
            return (Some(song.id), SongSource::PlayInfo);
        }
        let rect = iu_ocr::areas::result_title(frame.width(), frame.height());
        if let Some(lines) = rect.and_then(|rect| self.ocr.read_now(frame, rect, OCR_RESULT_WAIT)) {
            let found = if candidates.is_empty() {
                match_text(&lines, &songs.songs)
            } else {
                match_text(&lines, candidates.iter().copied())
            };
            if let Some(m) = found {
                return (Some(m.song.id.clone()), SongSource::ResultOcr);
            }
            tracing::info!(?lines, "result title read, but no song matched");
        }
        (None, SongSource::Unknown)
    }

    fn record_result(
        &mut self,
        frame: &RgbImage,
        r: ResultReading,
        s: ResultSymbols,
        title: Option<(TitleMask, u32)>,
    ) {
        // The shown result is cleared when a play starts, so the same screen
        // again without a play in between is one already recorded: the app
        // was restarted (or developer mode toggled) on the result screen.
        let shown = self.status.lock().expect("status lock").last_result.clone();
        if shown.is_some_and(|l| same_result(&l, &r, &s)) {
            tracing::info!("result screen already recorded; not recording it again");
            return;
        }
        let (song_id, source) = self.find_result_song(frame, &r, &s, title.as_ref());
        // Found some other way than the learned masks: learn this title.
        if let (Some(id), Some((mask, max_distance))) = (&song_id, &title)
            && !matches!(source, SongSource::LearnedTitle { .. })
        {
            self.learn_title(id, mask, *max_distance);
        }
        // The play before this result: its info box names this song too.
        if let Some(id) = &song_id {
            self.learn_play_title(id);
        }
        let matched = (song_id.is_some()).then_some(source);
        let mut record = ResultRecord {
            id: None,
            title: song_id
                .as_deref()
                .and_then(|id| song_list().get(id))
                .map(|s| s.title.clone()),
            game_day: self.day,
            recorded_at: Utc::now(),
            side: r.side,
            chart: s.chart,
            level: s.level,
            song_id,
            notes: r.notes,
            lamp: s.lamp,
            best_lamp: s.best_lamp.flatten(),
            dj_level: s.dj_level,
            best_dj_level: s.best_dj_level.flatten(),
            score: r.score,
            best_score: r.best_score,
            miss_count: r.miss_count,
            best_miss_count: r.best_miss_count,
            judge: r.judge,
            combo_break: r.combo_break,
            fast: r.fast,
            slow: r.slow,
            dead: s.dead.unwrap_or(false),
            use_option: s.use_option.flatten(),
        };
        // Cross-check with the play the counter just finished: the result
        // screen's PG..PR should match its last reading.
        let last = self.status.lock().expect("status lock").last_play.clone();
        let matches = last.as_ref().map(|p| {
            let j = record.judge;
            (p.judge.pg, p.judge.gr, p.judge.gd, p.judge.bd, p.judge.pr)
                == (j.pg, j.gr, j.gd, j.bd, j.pr)
        });
        tracing::info!(
            lamp = ?record.lamp,
            chart = ?record.chart,
            level = ?record.level,
            score = record.score,
            dj = ?record.dj_level,
            matches_last_play = ?matches,
            title = ?matched,
            "result recorded"
        );
        if let Some(store) = &self.store {
            let mask = title.as_ref().map(|(m, _)| mask_data(m));
            match store.insert_result(&record, mask.as_ref()) {
                Ok(id) => record.id = Some(id),
                Err(e) => tracing::error!("cannot save the result to data.db: {e}"),
            }
        }
        if record.song_id.is_none()
            && let Some(p) = &mut self.play_title
        {
            p.unnamed_result = record.id;
        }
        self.status.lock().expect("status lock").last_result = Some(record.clone());
        let _ = self.bus.send(Event::ResultRecorded(record));
        self.publish(true);
    }

    /// Feeds the counter; returns true if the reading was rejected.
    fn observe(&mut self, obs: Observation) -> bool {
        let events = self.counter.observe(obs);
        let mut rejected = false;
        let mut finished = None;
        for ev in &events {
            match ev {
                CounterEvent::PlayStarted { layout } => {
                    tracing::info!(%layout, "play started");
                    self.play_started = Some((Utc::now(), self.day));
                    // The shown result and song belong to the previous play.
                    {
                        let mut s = self.status.lock().expect("status lock");
                        s.last_result = None;
                        s.current_song = None;
                    }
                    self.play_title = None;
                    self.song_search = Some(SongSearch {
                        layout: *layout,
                        last_try: None,
                        tries: 0,
                    });
                }
                CounterEvent::PlayFinished { layout, judge } => {
                    tracing::info!(%layout, ?judge, notes = judge.notes_hit(), "play finished");
                    self.record_play(*layout, *judge);
                    // Entering and leaving without a single judgement keeps
                    // the previous song on screen.
                    if *judge != Judge::default() {
                        finished = Some(LastPlay::new(*layout, *judge));
                    }
                }
                CounterEvent::Rejected { reading, previous } => {
                    tracing::debug!(?reading, ?previous, "judge reading rejected");
                    rejected = true;
                }
                CounterEvent::JudgeUpdated { .. } => {}
            }
        }
        {
            let mut s = self.status.lock().expect("status lock");
            s.layout = self.counter.current.map(|c| c.layout.name().to_owned());
            s.current = self.counter.current.map(|c| c.judge);
            if finished.is_some() {
                s.last_play = finished;
            }
            s.today = self.counter.today_with_current();
            s.today_notes = s.today.notes_hit();
            s.plays_today = self.counter.plays_today;
        }
        let important = events
            .iter()
            .any(|e| !matches!(e, CounterEvent::JudgeUpdated { .. }));
        if important {
            self.publish(true);
        }
        rejected
    }

    fn dev_capture(&mut self, frame: &RgbImage, obs: &Observation, failed: bool) {
        if !self.config.dev_capture {
            self.pending_unreadable = None;
            self.before_play.clear();
            return;
        }
        let in_play = !matches!(obs, Observation::NotPlay);
        if !in_play {
            self.pending_unreadable = None;
        } else if self
            .pending_unreadable
            .as_ref()
            .is_some_and(|(at, _)| at.elapsed() >= DEV_CAPTURE_UNREADABLE_CONFIRM)
        {
            let (_, pending) = self.pending_unreadable.take().expect("checked above");
            spawn_save(pending, "unreadable");
        }

        // The song's Intro screen comes right before play: keep a frame a
        // second off the play screen, and when play starts save those older
        // than the fade-in (samples for title recognition on the Intro).
        if in_play {
            let now = Instant::now();
            for (at, f) in self.before_play.drain(..) {
                if now.duration_since(at) >= DEV_CAPTURE_INTRO_MIN_AGE {
                    spawn_save(f, "before-play");
                }
            }
        } else if self
            .before_play
            .back()
            .is_none_or(|(at, _)| at.elapsed() >= Duration::from_secs(1))
        {
            if self.before_play.len() == DEV_CAPTURE_INTRO_FRAMES {
                self.before_play.pop_front();
            }
            self.before_play.push_back((Instant::now(), frame.clone()));
        }

        if failed
            && self.pending_unreadable.is_none()
            && self.last_failure_capture.elapsed() >= DEV_CAPTURE_FAILURE_INTERVAL
        {
            self.last_failure_capture = Instant::now();
            self.pending_unreadable = Some((Instant::now(), frame.clone()));
        } else if in_play && self.last_play_capture.elapsed() >= DEV_CAPTURE_PLAY_INTERVAL {
            self.last_play_capture = Instant::now();
            spawn_save(frame.clone(), "play");
        }
    }

    fn roll_day(&mut self) {
        let today = game_day(Utc::now(), self.day_start_jst);
        if today != self.day {
            tracing::info!(%today, "new game day: resetting today's totals");
            self.day = today;
            self.counter.reset_day();
            {
                let mut s = self.status.lock().expect("status lock");
                s.last_play = None;
                s.last_result = None;
                s.today = self.counter.today_with_current();
                s.today_notes = s.today.notes_hit();
                s.plays_today = self.counter.plays_today;
            }
            self.publish(true);
        }
    }

    /// Writes a finished play to `data.db`, then announces it. Writing here
    /// rather than in a bus listener guarantees the row exists by the time
    /// listeners (e.g. the phone page reloading its list) see the event.
    /// Plays with no judgements at all (entered and left right away) are not
    /// worth a row.
    fn record_play(&mut self, layout: PlayLayout, judge: Judge) {
        let finished_at = Utc::now();
        let (started_at, game_day) = self.play_started.take().unwrap_or((finished_at, self.day));
        if judge == Judge::default() {
            return;
        }
        let record = PlayRecord {
            game_day,
            started_at,
            finished_at,
            layout,
            judge,
        };
        if let Some(store) = &self.store
            && let Err(e) = store.insert_play(&record)
        {
            tracing::error!("cannot save the play to data.db: {e}");
        }
        // No receivers is fine (nothing listening yet).
        let _ = self.bus.send(Event::PlayFinished(record));
    }

    fn publish(&mut self, force: bool) {
        if !force && self.last_emit.elapsed() < STATUS_INTERVAL {
            return;
        }
        self.last_emit = Instant::now();
        let snapshot = {
            let mut s = self.status.lock().expect("status lock");
            s.sender = self.config.spout_sender.clone();
            s.dev_capture = self.config.dev_capture;
            s.clone()
        };
        let _ = self.bus.send(Event::Status(Box::new(snapshot)));
    }
}

/// Saves a dev capture on a worker thread: PNG encoding takes tens of ms
/// and must not stall the capture loop.
fn spawn_save(frame: RgbImage, reason: &'static str) {
    std::thread::spawn(move || {
        if let Err(e) = save_dev_capture(&frame, reason) {
            tracing::warn!("dev capture failed: {e}");
        }
    });
}

/// Cheap fingerprint of a frame: a sparse sample of pixels.
fn fingerprint(frame: &RgbImage) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    frame
        .as_raw()
        .iter()
        .step_by(997)
        .for_each(|b| b.hash(&mut h));
    h.finish()
}

fn summary_of(store: Option<&Store>, day: NaiveDate) -> Option<DaySummary> {
    store?
        .day_summary(day)
        .inspect_err(|e| tracing::error!("cannot read today's plays from data.db: {e}"))
        .ok()
}

/// `<Pictures>\INFINITAS Screenshots\dev-capture\<w>x<h>\unsorted\`.
pub fn dev_capture_dir(width: u32, height: u32) -> Option<PathBuf> {
    dirs::picture_dir().map(|p| {
        p.join("INFINITAS Screenshots")
            .join("dev-capture")
            .join(format!("{width}x{height}"))
            .join("unsorted")
    })
}

fn save_dev_capture(frame: &RgbImage, reason: &str) -> Result<PathBuf, Box<dyn std::error::Error>> {
    let dir = dev_capture_dir(frame.width(), frame.height()).ok_or("no Pictures folder")?;
    std::fs::create_dir_all(&dir)?;
    let name = format!("{}_{reason}.png", Local::now().format("%Y%m%d_%H%M%S_%3f"));
    let path = dir.join(name);
    frame.save(&path)?;
    tracing::info!(path = %path.display(), "dev capture saved");
    Ok(path)
}

fn mask_data(mask: &TitleMask) -> TitleMaskData {
    TitleMaskData {
        width: mask.width(),
        height: mask.height(),
        bytes: mask.to_bytes(),
    }
}

/// Whether a stored result is this reading of the result screen.
fn same_result(stored: &ResultRecord, r: &ResultReading, s: &ResultSymbols) -> bool {
    stored.side == r.side
        && stored.notes == r.notes
        && stored.score == r.score
        && stored.judge == r.judge
        && stored.combo_break == r.combo_break
        && stored.fast == r.fast
        && stored.slow == r.slow
        && stored.chart == s.chart
        && stored.lamp == s.lamp
}

/// How a result's song was found (logged).
#[derive(Debug, Clone, Copy, PartialEq)]
enum SongSource {
    OnlyCandidate,
    LearnedTitle { distance: u32 },
    PlayInfo,
    ResultOcr,
    Unknown,
}

/// Looking for the current play's song on the play screen.
struct SongSearch {
    /// The play's layout: where its info box is, and SP or DP.
    layout: PlayLayout,
    last_try: Option<Instant>,
    tries: u32,
}
