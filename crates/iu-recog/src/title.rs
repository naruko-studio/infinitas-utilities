//! Song titles on the result screen.
//!
//! The title line under the score panels is grey text (with a dark outline)
//! on a red or blue background, centred, at the same place for both sides
//! and both play styles. A title is recognized by binarizing that line
//! ("grey enough and light enough") and comparing the whole mask with the
//! masks of the candidate songs: the chart, level and NOTES count read from
//! the same screen already narrow the song list down to a few songs.
//!
//! Masks of known titles come from our own labelled screenshots
//! (`resources/<w>x<h>/titles.json`, generated by `tools/resgen`) and from
//! what the user's app learned while playing.

use std::fmt;

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as BASE64;
use image::RgbImage;
use iu_core::{PlayLayout, Side};
use serde::{Deserialize, Deserializer, Serialize, Serializer};

pub const RESOURCE_VERSION: u32 = 1;

/// Where the title line is drawn.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct TitleArea {
    pub x: u32,
    pub y: u32,
    pub width: u32,
    pub height: u32,
}

/// Play screen: the title line of the song info box (the artist line under
/// it is left out). The text is the same neutral grey as on the result
/// screen, on a dark grey box, so [`TitleMask::from_image`] binarizes it
/// as is (the box is dark enough to count as outline everywhere). Centred
/// above the BGA on SP (rows 67–90, the artist from 99), left-aligned on DP
/// (rows 57–80, the artist from 96; the DP-left box is cut short of the
/// gauge column on its right). The text is static, so a song's mask is the
/// same every play in the same layout; masks of different layouts are kept
/// apart (SP centres may be a pixel or two off between layouts).
pub fn play_title_area(width: u32, height: u32, layout: PlayLayout) -> Option<TitleArea> {
    if (width, height) != (1920, 1080) {
        return None;
    }
    const SP_WIDTH: u32 = 640;
    const DP_WIDTH: u32 = 390;
    const HEIGHT: u32 = 34;
    const TOP_SP: u32 = 62;
    const TOP_DP: u32 = 52;
    let centred = |centre: u32, top: u32| TitleArea {
        x: centre - SP_WIDTH / 2,
        y: top,
        width: SP_WIDTH,
        height: HEIGHT,
    };
    Some(match layout {
        PlayLayout::Sp {
            side: Side::P1,
            graph_inner: true,
        } => centred(1440, TOP_SP),
        PlayLayout::Sp {
            side: Side::P1,
            graph_inner: false,
        } => centred(1024, TOP_SP),
        PlayLayout::Sp {
            side: Side::P2,
            graph_inner: true,
        } => centred(480, TOP_SP),
        PlayLayout::Sp {
            side: Side::P2,
            graph_inner: false,
        } => centred(898, TOP_SP),
        PlayLayout::Dp { info_left: true } => TitleArea {
            x: 0,
            y: TOP_DP,
            width: DP_WIDTH,
            height: HEIGHT,
        },
        PlayLayout::Dp { info_left: false } => TitleArea {
            x: 1530,
            y: TOP_DP,
            width: DP_WIDTH,
            height: HEIGHT,
        },
    })
}

/// The title text is exactly neutral grey (R = G = B, ±1 for Spout) and
/// light. The red and blue backgrounds are far from grey; their light
/// streaks are close but tinted by a few levels.
pub fn is_title_ink([r, g, b]: [u8; 3]) -> bool {
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    min >= 100 && max - min <= 2
}

/// The text's black outline. The backgrounds never get this dark.
fn is_outline([r, g, b]: [u8; 3]) -> bool {
    r.max(g).max(b) < 40
}

/// How far from a grey pixel the outline must be: the strokes are a few
/// pixels wide.
const OUTLINE_REACH: i64 = 3;

/// A binarized title line, bit-packed (row-major, 64 pixels per word).
#[derive(Clone, PartialEq, Eq)]
pub struct TitleMask {
    width: u32,
    height: u32,
    words: Vec<u64>,
}

impl fmt::Debug for TitleMask {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "TitleMask({}x{}, {} on)",
            self.width,
            self.height,
            self.count_ones()
        )
    }
}

impl TitleMask {
    /// Grey pixels with the black outline nearby (on the same row or
    /// column): the title's letters, not the background's light streaks.
    pub fn from_image(img: &RgbImage, area: TitleArea) -> Self {
        let pixel = |x: i64, y: i64| -> Option<[u8; 3]> {
            let (x, y) = (u32::try_from(x).ok()?, u32::try_from(y).ok()?);
            img.get_pixel_checked(x, y).map(|p| p.0)
        };
        let outlined = |x: i64, y: i64| {
            (1..=OUTLINE_REACH).any(|d| {
                [(d, 0), (-d, 0), (0, d), (0, -d)]
                    .into_iter()
                    .any(|(dx, dy)| pixel(x + dx, y + dy).is_some_and(is_outline))
            })
        };
        let mut words = vec![0u64; Self::word_count(area.width, area.height)];
        for j in 0..area.height {
            for i in 0..area.width {
                let (x, y) = (i64::from(area.x + i), i64::from(area.y + j));
                let on = pixel(x, y).is_some_and(is_title_ink) && outlined(x, y);
                if on {
                    let n = (j * area.width + i) as usize;
                    words[n / 64] |= 1 << (n % 64);
                }
            }
        }
        Self {
            width: area.width,
            height: area.height,
            words,
        }
    }

    fn word_count(width: u32, height: u32) -> usize {
        ((width * height) as usize).div_ceil(64)
    }

    pub fn width(&self) -> u32 {
        self.width
    }

    pub fn height(&self) -> u32 {
        self.height
    }

    /// Whether the pixel at (`x`, `y`) of the area is ink.
    pub fn get(&self, x: u32, y: u32) -> bool {
        if x >= self.width || y >= self.height {
            return false;
        }
        let n = (y * self.width + x) as usize;
        self.words[n / 64] >> (n % 64) & 1 == 1
    }

    pub fn count_ones(&self) -> u32 {
        self.words.iter().map(|w| w.count_ones()).sum()
    }

    /// Number of differing pixels; `u32::MAX` for masks of different sizes
    /// (from another area: never the same title).
    pub fn distance(&self, other: &TitleMask) -> u32 {
        if (self.width, self.height) != (other.width, other.height) {
            return u32::MAX;
        }
        self.words
            .iter()
            .zip(&other.words)
            .map(|(a, b)| (a ^ b).count_ones())
            .sum()
    }

    /// Little-endian bytes of the packed words, for storage.
    pub fn to_bytes(&self) -> Vec<u8> {
        self.words.iter().flat_map(|w| w.to_le_bytes()).collect()
    }

    pub fn from_bytes(width: u32, height: u32, bytes: &[u8]) -> Option<Self> {
        let n = Self::word_count(width, height);
        if bytes.len() != n * 8 {
            return None;
        }
        let words = bytes
            .as_chunks::<8>()
            .0
            .iter()
            .map(|&c| u64::from_le_bytes(c))
            .collect();
        Some(Self {
            width,
            height,
            words,
        })
    }
}

/// JSON form: `{ "width", "height", "bits": base64 of the packed words }`.
#[derive(Serialize, Deserialize)]
struct TitleMaskRepr {
    width: u32,
    height: u32,
    bits: String,
}

impl Serialize for TitleMask {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        TitleMaskRepr {
            width: self.width,
            height: self.height,
            bits: BASE64.encode(self.to_bytes()),
        }
        .serialize(s)
    }
}

impl<'de> Deserialize<'de> for TitleMask {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let r = TitleMaskRepr::deserialize(d)?;
        let bytes = BASE64.decode(r.bits).map_err(serde::de::Error::custom)?;
        TitleMask::from_bytes(r.width, r.height, &bytes)
            .ok_or_else(|| serde::de::Error::custom("title mask has the wrong length"))
    }
}

/// One known title mask.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KnownTitle {
    pub song_id: String,
    pub mask: TitleMask,
}

/// `resources/<w>x<h>/titles.json`.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TitleResources {
    pub version: u32,
    pub width: u32,
    pub height: u32,
    pub area: TitleArea,
    /// A title further than this from every known mask is unknown.
    pub max_distance: u32,
    pub titles: Vec<KnownTitle>,
}

#[derive(Debug, thiserror::Error)]
pub enum TitleResourceError {
    #[error("title resources are not valid JSON: {0}")]
    Json(#[from] serde_json::Error),
    #[error("title resources are version {0}, this build reads {RESOURCE_VERSION}")]
    Version(u32),
}

impl TitleResources {
    pub fn from_json(json: &str) -> Result<Self, TitleResourceError> {
        let res: Self = serde_json::from_str(json)?;
        if res.version != RESOURCE_VERSION {
            return Err(TitleResourceError::Version(res.version));
        }
        Ok(res)
    }

    /// The title line of a result screen of this resolution.
    pub fn mask(&self, img: &RgbImage) -> Option<TitleMask> {
        (img.dimensions() == (self.width, self.height))
            .then(|| TitleMask::from_image(img, self.area))
    }
}

/// The closest known title among `known` whose song is a candidate, if
/// within `max_distance`. With no candidates given, every song is one.
pub fn best_match<'a>(
    mask: &TitleMask,
    known: impl IntoIterator<Item = &'a KnownTitle>,
    candidates: Option<&[&str]>,
    max_distance: u32,
) -> Option<(&'a str, u32)> {
    known
        .into_iter()
        .filter(|k| candidates.is_none_or(|c| c.contains(&k.song_id.as_str())))
        .map(|k| (k.song_id.as_str(), mask.distance(&k.mask)))
        .filter(|&(_, d)| d <= max_distance)
        .min_by_key(|&(_, d)| d)
}

/// How the song of a result screen was found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum TitleMatch {
    /// Only one song has this chart, level and NOTES count: no need to
    /// look at the title (and its mask can be learned).
    OnlyCandidate(String),
    /// The closest known title mask among the candidates.
    Recognized { song_id: String, distance: u32 },
    /// Several candidates and no known mask close enough: ask the user.
    Unknown,
}

/// Picks the song of a result screen. `candidates` are the song IDs the
/// chart, level and NOTES count allow (empty: the song list does not know
/// this count, so any known title may match).
pub fn identify<'a>(
    mask: &TitleMask,
    known: impl IntoIterator<Item = &'a KnownTitle>,
    candidates: &[&str],
    max_distance: u32,
) -> TitleMatch {
    if let [only] = candidates {
        return TitleMatch::OnlyCandidate((*only).to_owned());
    }
    let restrict = (!candidates.is_empty()).then_some(candidates);
    match best_match(mask, known, restrict, max_distance) {
        Some((id, distance)) => TitleMatch::Recognized {
            song_id: id.to_owned(),
            distance,
        },
        None => TitleMatch::Unknown,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use image::Rgb;

    fn area() -> TitleArea {
        TitleArea {
            x: 1,
            y: 1,
            width: 70,
            height: 2,
        }
    }

    fn img(grey_at: &[(u32, u32)]) -> RgbImage {
        // Black: every grey pixel is next to the "outline".
        let mut img = RgbImage::from_pixel(80, 4, Rgb([0, 0, 0]));
        for &(x, y) in grey_at {
            img.put_pixel(x, y, Rgb([200, 200, 200]));
        }
        img
    }

    #[test]
    fn grey_is_ink_and_colors_are_not() {
        assert!(is_title_ink([200, 200, 201]));
        assert!(!is_title_ink([141, 145, 144])); // a tinted streak
        assert!(!is_title_ink([180, 20, 20])); // red background
        assert!(!is_title_ink([40, 90, 220])); // blue background
        assert!(!is_title_ink([60, 60, 60])); // outline
    }

    #[test]
    fn grey_without_an_outline_is_background() {
        let mut img = RgbImage::from_pixel(80, 4, Rgb([40, 90, 220]));
        img.put_pixel(5, 1, Rgb([200, 200, 200])); // a streak on blue
        img.put_pixel(20, 1, Rgb([200, 200, 200]));
        img.put_pixel(22, 1, Rgb([0, 0, 0])); // a letter's outline
        let m = TitleMask::from_image(&img, area());
        assert_eq!(m.count_ones(), 1);
    }

    #[test]
    fn distance_counts_differing_pixels_and_round_trips() {
        let a = TitleMask::from_image(&img(&[(1, 1), (70, 2)]), area());
        let b = TitleMask::from_image(&img(&[(1, 1), (5, 1)]), area());
        assert_eq!(a.count_ones(), 2);
        assert_eq!(a.distance(&b), 2);
        assert_eq!(a.distance(&a), 0);
        let json = serde_json::to_string(&a).unwrap();
        assert_eq!(serde_json::from_str::<TitleMask>(&json).unwrap(), a);
        let other = TitleMask::from_image(
            &img(&[]),
            TitleArea {
                width: 10,
                ..area()
            },
        );
        assert_eq!(a.distance(&other), u32::MAX);
    }

    #[test]
    fn best_match_respects_candidates_and_threshold() {
        let a = TitleMask::from_image(&img(&[(1, 1), (2, 1), (3, 1)]), area());
        let b = TitleMask::from_image(&img(&[(40, 2), (41, 2)]), area());
        let known = [
            KnownTitle {
                song_id: "a".into(),
                mask: a.clone(),
            },
            KnownTitle {
                song_id: "b".into(),
                mask: b,
            },
        ];
        assert_eq!(best_match(&a, &known, None, 0), Some(("a", 0)));
        assert_eq!(best_match(&a, &known, Some(&["b"]), 10), Some(("b", 5)));
        assert_eq!(best_match(&a, &known, Some(&["b"]), 4), None);

        assert_eq!(
            identify(&b_far(), &known, &["x"], 0),
            TitleMatch::OnlyCandidate("x".into())
        );
        assert_eq!(
            identify(&a, &known, &["a", "b"], 10),
            TitleMatch::Recognized {
                song_id: "a".into(),
                distance: 0
            }
        );
        assert_eq!(
            identify(&b_far(), &known, &["a", "b"], 1),
            TitleMatch::Unknown
        );
        // No candidates: every known title may match.
        assert!(matches!(
            identify(&a, &known, &[], 10),
            TitleMatch::Recognized { .. }
        ));
    }

    fn b_far() -> TitleMask {
        TitleMask::from_image(&img(&[(60, 1), (61, 1), (62, 1), (63, 1)]), area())
    }
}
